#!/usr/bin/env python3
"""
image/ 폴더를 훑어서 Js/images.js (사이트의 사진 목록)를 갱신한다.

- 새 사진은 다음 번호(IR-13, IR-14 ...)를 받아 목록 끝에 붙는다.
- 이미 있는 사진의 번호는 바뀌지 않는다.
- 내용이 똑같은 파일(중복)은 하나만 남긴다. "이름 (1).webp" 같은 사본은 건너뛴다.
- HEIC 사진은 브라우저가 못 읽으므로 같은 이름의 .jpg 로 바꿔서 쓴다.
- 폴더에서 지운 사진은 목록에서도 빠진다.

사용법
  python3 tools/sync_images.py           목록만 갱신
  python3 tools/sync_images.py --push    갱신 후 바뀐 게 있으면 커밋하고 GitHub 에 올린다
"""
import hashlib
import json
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IMAGE_DIR = ROOT / "image"
MANIFEST = ROOT / "Js" / "images.js"
WEB_EXT = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"}
CONVERT_EXT = {".heic", ".heif"}
HEADER = "// Generated by tools/sync_images.py. Do not edit by hand.\nconst IMAGES = "


def log(msg):
    print(f"[sync_images] {msg}", flush=True)


def read_manifest():
    if not MANIFEST.exists():
        return []
    text = MANIFEST.read_text(encoding="utf-8")
    body = text[text.index("["):text.rindex("]") + 1]
    return json.loads(body)


def write_manifest(entries):
    lines = ",\n".join("  " + json.dumps(e, ensure_ascii=False) for e in entries)
    MANIFEST.write_text(f"{HEADER}[\n{lines}\n];\n", encoding="utf-8")


def file_hash(path):
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def size_of(path):
    out = subprocess.run(["/usr/bin/sips", "-g", "pixelWidth", "-g", "pixelHeight", str(path)],
                         capture_output=True, text=True).stdout
    w = re.search(r"pixelWidth:\s*(\d+)", out)
    h = re.search(r"pixelHeight:\s*(\d+)", out)
    return (int(w.group(1)), int(h.group(1))) if w and h else (None, None)


def is_copy_name(name):
    # "photo (1).webp", "photo copy.webp", "photo 2.webp" style duplicates sort last
    return bool(re.search(r"( \(\d+\)| copy( \d+)?| \d+)$", Path(name).stem))


def wait_until_stable(paths, seconds=2):
    # A file that is still being copied keeps growing; wait for sizes to settle
    before = {p: p.stat().st_size for p in paths if p.exists()}
    time.sleep(seconds)
    return all(p.exists() and p.stat().st_size == before.get(p) for p in paths)


def convert_heic():
    for p in IMAGE_DIR.iterdir():
        if p.suffix.lower() in CONVERT_EXT:
            target = p.with_suffix(".jpg")
            if not target.exists():
                subprocess.run(["/usr/bin/sips", "-s", "format", "jpeg", str(p), "--out", str(target)],
                               capture_output=True)
                log(f"converted {p.name} -> {target.name}")


def sync():
    convert_heic()
    files = [p for p in IMAGE_DIR.iterdir() if p.is_file() and p.suffix.lower() in WEB_EXT]
    for _ in range(5):
        if wait_until_stable(files):
            break

    old = read_manifest()
    by_file = {e["file"]: e for e in old}
    kept = [e for e in old if (IMAGE_DIR / e["file"]).exists()]
    removed = [e["file"] for e in old if e not in kept]

    seen = {}
    for e in kept:
        e.setdefault("hash", file_hash(IMAGE_DIR / e["file"]))
        seen[e["hash"]] = e["file"]

    numbers = [int(m.group(1)) for e in old if (m := re.match(r"IR-(\d+)$", e["id"]))]
    next_no = max(numbers, default=0) + 1

    added, skipped = [], []
    candidates = sorted((p for p in files if p.name not in by_file),
                        key=lambda p: (is_copy_name(p.name), p.name))
    for p in candidates:
        digest = file_hash(p)
        if digest in seen:
            skipped.append(f"{p.name} (same as {seen[digest]})")
            continue
        w, h = size_of(p)
        if not w:
            skipped.append(f"{p.name} (could not read size)")
            continue
        entry = {"id": f"IR-{next_no:02d}", "file": p.name, "w": w, "h": h, "hash": digest}
        next_no += 1
        kept.append(entry)
        seen[digest] = p.name
        added.append(entry)

    changed = bool(added or removed) or any("hash" not in e for e in old)
    if changed:
        write_manifest(kept)
    for e in added:
        log(f"added {e['id']}  {e['file']}")
    for name in removed:
        log(f"removed {name}")
    for s in skipped:
        log(f"skipped {s}")
    log(f"{len(kept)} photographs in the archive")
    return added, removed, kept


def git(*args):
    return subprocess.run(["/usr/bin/git", "-C", str(ROOT), *args], capture_output=True, text=True)


def push(added, removed, kept):
    paths = ["Js/images.js"] + [f"image/{e['file']}" for e in kept]
    git("add", "--", *paths)
    for name in removed:
        git("rm", "--cached", "--ignore-unmatch", "-q", f"image/{name}")
    if not git("diff", "--cached", "--quiet").returncode:
        log("nothing new to publish")
        return
    parts = []
    if added:
        parts.append(f"Add {len(added)} photograph{'s' if len(added) > 1 else ''}")
    if removed:
        parts.append(f"remove {len(removed)}")
    message = ", ".join(parts) or "Update photograph list"
    result = git("commit", "-q", "-m", message)
    if result.returncode:
        log("commit failed: " + result.stderr.strip())
        return
    result = git("push", "-q", "origin", "HEAD")
    log("published to GitHub" if not result.returncode else "push failed: " + result.stderr.strip())


if __name__ == "__main__":
    a, r, k = sync()
    if "--push" in sys.argv:
        push(a, r, k)
